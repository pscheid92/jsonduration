// gen_wrapper_types writes wrapper_types.go: one wrapper type per format.
// Run it with go generate.
package main

import (
	"bytes"
	"go/format"
	"log"
	"os"
	"text/template"
)

// types lists one wrapper per format, with the encoding of 1h30m0.5s.
var types = []struct {
	Name, Format, Kind, Example string
}{
	{"UnitsDuration", "Units", "string", `"1h30m0.5s"`},
	{"SecDuration", "Sec", "number", "5400.5"},
	{"MilliDuration", "Milli", "number", "5400500"},
	{"MicroDuration", "Micro", "number", "5400500000"},
	{"NanoDuration", "Nano", "number", "5400500000000"},
	{"ISO8601Duration", "ISO8601", "string", `"PT1H30M0.5S"`},
}

var tmpl = template.Must(template.New("").Parse(`// Copyright 2026 Patrick Scheid. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE file.

// Code generated by gen_wrapper_types.go; DO NOT EDIT.

package jsonduration

import (
	"encoding/json/jsontext"
	"time"
)
{{range .}}
// {{.Name}} is a [time.Duration] that encodes itself in format [{{.Format}}]
// in encoding/json/v2, without any options: as a JSON {{.Kind}} such as
// {{.Example}} for 1h30m0.5s.
type {{.Name}} struct{ time.Duration }

// MarshalJSONTo implements [encoding/json/v2.MarshalerTo].
func (d {{.Name}}) MarshalJSONTo(enc *jsontext.Encoder) error {
	return encode(enc, {{.Format}}, d.Duration)
}

// UnmarshalJSONFrom implements [encoding/json/v2.UnmarshalerFrom].
func (d *{{.Name}}) UnmarshalJSONFrom(dec *jsontext.Decoder) error {
	return decoders[{{.Format}}].decode(dec, &d.Duration)
}
{{end}}`))

func main() {
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, types); err != nil {
		log.Fatal(err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("wrapper_types.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
